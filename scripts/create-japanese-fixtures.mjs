const augment = texts => texts.flatMap(text => [text, `すみません、${text}`, `${text.replace(/[。！？!?]+$/u, '')}。よろしくお願いします。`]);
const spec = {
  name: 'support-inbox-japanese',
  provenance: 'Assistant-authored Japanese examples: 150 base phrases, three training-only variants each. No external teacher API. Japanese calibration and exam authored separately and frozen before training. Same architecture/settings as the English baseline. Single-intent refund/support/sales routing; ambiguous, mixed-intent and out-of-scope requests should abstain.',
  branches: Object.entries(descriptions).map(([id, description]) => ({ id, description, examples: augment(examples[id]) })),
  fallbackExamples: augment(examples.__fallback), calibration,
};
const normalize = text => text.normalize('NFKC').toLowerCase().replace(/\s+/gu, '').replace(/[。、！？!?.,]/gu, '');
const training = [...spec.branches.flatMap(branch => branch.examples), ...spec.fallbackExamples];
const seen = new Set(training.map(normalize));
if (seen.size !== training.length) throw new Error('Duplicate normalized training examples');
for (const row of [...calibration, ...exam]) {
  if (seen.has(normalize(row.text))) throw new Error(`Split overlap: ${row.text}`);
  seen.add(normalize(row.text));
}
await writeFile(new URL('../examples/support.ja.switch.json', import.meta.url), JSON.stringify(spec, null, 2) + '\n');
await writeFile(new URL('../examples/support.ja.test.json', import.meta.url), JSON.stringify(exam, null, 2) + '\n');
console.log(`Japanese fixtures: ${training.length} training, ${calibration.length} calibration, ${exam.length} exam`);
