#!/usr/bin/env node
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { resolve, dirname, extname } from 'node:path';
import { pathToFileURL } from 'node:url';
import { createHash } from 'node:crypto';
import { gzipSync, brotliCompressSync } from 'node:zlib';
import { train, calibrate } from '../src/train.mjs';
import { declarations } from '../src/declarations.mjs';

const [command, specPath, flag, outputPath] = process.argv.slice(2);
if (command !== 'compile' || !specPath || flag !== '--out' || !outputPath) {
  console.error('Usage: node bin/picklet.mjs compile switch.ts --out model.mjs');
  process.exitCode = 1;
} else {
  const started = performance.now();
  if (extname(outputPath) !== '.mjs') throw new Error('Output must end in .mjs (types are emitted as .d.mts)');
  if (!['.json', '.mjs', '.ts', '.mts'].includes(extname(specPath))) throw new Error('Definition must be .ts, .mts, .mjs or .json');
  const spec = extname(specPath) === '.json'
    ? JSON.parse(await readFile(resolve(specPath), 'utf8'))
    : (await import(pathToFileURL(resolve(specPath)).href)).default;
  const { model, floatScores, quantizedScores } = train(spec);
  const calibrated = calibrate(spec, quantizedScores);
  model.policy = calibrated.policy;
  model.training.specSha256 = createHash('sha256').update(JSON.stringify(spec)).digest('hex');
  const parityRows = [...spec.branches.flatMap(b => b.examples), ...spec.fallbackExamples, ...spec.calibration.map(row => row.text)];
  let maxScoreDifference = 0, changedWinners = 0;
  const argmax = scores => scores.indexOf(Math.max(...scores));
  for (const text of parityRows) {
    const full = floatScores(text), small = quantizedScores(text);
    if (argmax(full) !== argmax(small)) changedWinners++;
    full.forEach((value, i) => { maxScoreDifference = Math.max(maxScoreDifference, Math.abs(value - small[i])); });
  }
  const runtime = (await readFile(new URL('../src/runtime.mjs', import.meta.url), 'utf8')).replace(/^export /gm, '');
  const source = `// Generated by picklet. Weights, tokenizer, and inference are all inline.\n${runtime}\nconst model = ${JSON.stringify(model)};\nconst predictor = makeSwitch(model);\nexport default predictor;\n`;
  const report = {
    name: spec.name, parameters: model.buckets * (model.branches.length + 1) + model.bias.length,
    weightBytes: model.buckets * (model.branches.length + 1), artifactBytes: Buffer.byteLength(source),
    gzipBytes: gzipSync(source).length, brotliBytes: brotliCompressSync(source).length,
    training: model.training, calibration: calibrated.calibration, policy: model.policy,
    quantization: { checked: parityRows.length, changedWinners, maxScoreDifference },
    compileMs: performance.now() - started,
  };
  await mkdir(dirname(resolve(outputPath)), { recursive: true });
  await writeFile(resolve(outputPath), source);
  await writeFile(resolve(outputPath).replace(/\.mjs$/, '.d.mts'), declarations(model));
  await writeFile(resolve(outputPath).replace(/\.mjs$/, '') + '.report.json', JSON.stringify(report, null, 2) + '\n');
  console.log(`✓ Trained ${spec.name} on ${model.training.examples} examples`);
  console.log(`✓ Exported ${report.parameters.toLocaleString()} parameters; ${report.brotliBytes.toLocaleString()} bytes Brotli including runtime`);
  console.log(`✓ Quantization: ${changedWinners} changed winners across ${parityRows.length} training/calibration cases`);
  console.log(`✓ Calibration: ${report.calibration.accepted}/${report.calibration.count} accepted, ${report.calibration.acceptedErrors} accepted errors`);
  console.log(`✓ ${resolve(outputPath)} (${Math.round(report.compileMs)} ms)`);
}
